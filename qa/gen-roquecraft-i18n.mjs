// ── Escrita ─────────────────────────────────────────────────────────────────
//
// ⚠️ O GERADOR FORMATA O QUE ESCREVE, e isso não é capricho: `serialize` põe
// toda string numa linha só, e o prettier quebra as longas em duas. Enquanto a
// formatação era feita à mão depois, `yarn format:check` ficava vermelho toda
// vez que alguém rodava o gerador — e o portão passava a depender de lembrar de
// rodar o prettier em seguida. Portão que depende de memória não é portão.
async function comPrettier(texto, arquivo) {
  try {
    const prettier = await import('prettier')
    const config = (await prettier.resolveConfig(arquivo)) || {}
    return await prettier.format(texto, { ...config, filepath: arquivo })
  } catch {
    return texto
  }
}

function setDeep(obj, path, value) {
  const parts = path.split('.')
  let cur = obj
  for (let i = 0; i < parts.length - 1; i++) {
    cur[parts[i]] = cur[parts[i]] || {}
    cur = cur[parts[i]]
  }
  cur[parts.at(-1)] = value
}

const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`

function serialize(obj, indent = 2) {
  const pad = ' '.repeat(indent)
  const lines = []
  for (const [k, v] of Object.entries(obj)) {
    const key = /^[A-Za-z_$][\w$]*$/.test(k) ? k : q(k)
    if (v && typeof v === 'object') {
      lines.push(`${pad}${key}: {`)
      lines.push(serialize(v, indent + 2))
      lines.push(`${pad}},`)
    } else {
      lines.push(`${pad}${key}: ${q(v)},`)
    }
  }
  return lines.join('\n')
}

