// idiomas, em silêncio — e `node scripts/i18n.js check` continuou VERDE,
// porque as dez ficaram igualmente mutiladas. Só um teste de conteúdo pegou.
//
// Então o gerador passa a se recusar a escrever quando o que ele tem é MENOS
// do que o que já está no disco. Ou a chave volta pra tabela, ou o gerador não
// roda. Nunca mais em silêncio.
async function chavesDoArquivo(caminho) {
  if (!existsSync(caminho)) return []
  const mod = await import(pathToFileURL(caminho).href + `?v=${Date.now()}`)
  const fora = []
  const anda = (o, prefixo) => {
    for (const [k, v] of Object.entries(o || {})) {
      if (v && typeof v === 'object') anda(v, `${prefixo}${k}.`)
      else fora.push(`${prefixo}${k}`)
    }
  }
  anda(mod.default, '')
  return fora
}

